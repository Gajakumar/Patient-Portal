public class WaitStory {
	
	@Keyword
	def waitForElementText(TestObject to, int timeout = 20) {
		WebUI.waitForElementVisible(to, timeout)
		
		String text = ""
		int elapsed = 0

		while (elapsed < timeout) {
			text = WebUI.getText(to)
			if (text?.trim()) {
				return true
			}
			WebUI.delay(1)
			elapsed++
		}

		throw new Exception("Text not found in element within ${timeout} seconds")
	}

}
